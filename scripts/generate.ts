/**
 * Generates src/generated/<service>.ts from wsdl/<service>.wsdl: the runtime
 * schema the SOAP layer uses to build requests in WSDL order and decode
 * responses, plus TypeScript types for every operation.
 *
 *   node scripts/generate.ts
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { children, child, parseXml, type XmlElement } from '../src/xml.ts';
import type { Field, FieldType, Operation, ServiceSchema } from '../src/schema.ts';

const SERVICES = [
  { service: 'taxpayer', wsdl: 'wsdl/taxpayer.wsdl' },
  { service: 'waybill', wsdl: 'wsdl/waybill.wsdl' },
  { service: 'invoices', wsdl: 'wsdl/invoices.wsdl' },
] as const;

const SCALARS = new Set(['string', 'int', 'long', 'decimal', 'double', 'boolean', 'dateTime', 'base64Binary']);

function fieldsOf(complexType: XmlElement | undefined): Field[] {
  const sequence = complexType && child(complexType, 'sequence');
  if (!sequence) return [];
  return sequence.children.flatMap((el): Field[] => {
    if (el.name === 'any') return [];
    const name = el.attrs.name;
    if (!name) throw new Error(`Unnamed element in ${complexType.attrs.name ?? 'inline type'}`);
    return [{ name, type: typeOf(el), ...(el.attrs.maxOccurs === 'unbounded' && { list: true as const }) }];
  });
}

function typeOf(el: XmlElement): FieldType {
  const declared = el.attrs.type;
  if (!declared) return 'any';
  const [prefix, local] = declared.includes(':') ? declared.split(':') : ['', declared];
  if (prefix === 's' && SCALARS.has(local!)) return local as FieldType;
  if (prefix === 'tns') return `#${local}`;
  throw new Error(`Unsupported type ${declared}`);
}

function schemaOf(service: string, wsdl: XmlElement): ServiceSchema {
  const schema = child(child(wsdl, 'types')!, 'schema')!;
  const namespace = schema.attrs.targetNamespace!;
  const address = child(child(child(wsdl, 'service')!, 'port')!, 'address')!;

  const types: Record<string, Field[]> = {};
  const arrays: Record<string, Field> = {};
  for (const ct of children(schema, 'complexType')) {
    const fields = fieldsOf(ct);
    const name = ct.attrs.name!;
    if (name.startsWith('ArrayOf') && fields.length === 1 && fields[0]!.list) arrays[name] = fields[0]!;
    else types[name] = fields;
  }

  const elements = new Map(children(schema, 'element').map((el) => [el.attrs.name!, el]));
  const operations: Record<string, Operation> = {};
  const binding = children(wsdl, 'binding').find((b) => child(b, 'binding')?.attrs.transport && b.attrs.name?.endsWith('Soap'))!;
  for (const op of children(binding, 'operation')) {
    const name = op.attrs.name!;
    if (operations[name]) continue;
    operations[name] = {
      action: child(op, 'operation')!.attrs.soapAction!,
      input: fieldsOf(child(elements.get(name)!, 'complexType')),
      output: fieldsOf(child(elements.get(`${name}Response`)!, 'complexType')),
    };
  }

  return { service, endpoint: address.attrs.location!, namespace, types, arrays, operations };
}

const pascal = (s: string) => s.replace(/(^|_)([a-zA-Z])/g, (_, __, c: string) => c.toUpperCase());

function tsType(field: Field, schema: ServiceSchema, direction: 'in' | 'out'): string {
  const base = ((): string => {
    switch (field.type) {
      case 'string':
      case 'dateTime':
      case 'base64Binary':
        return 'string';
      case 'decimal':
      case 'double':
        return direction === 'in' ? 'string | number' : 'string';
      case 'int':
      case 'long':
        return 'number';
      case 'boolean':
        return 'boolean';
      case 'any':
        return direction === 'in' ? 'RawXml' : 'XmlElement';
      default: {
        const ref = field.type.slice(1);
        const item = schema.arrays[ref];
        return item ? `${tsType({ name: item.name, type: item.type }, schema, direction)}[]` : ref;
      }
    }
  })();
  return field.list ? `${base}[]` : base;
}

/** One line per type and per operation, so a WSDL change shows up as a readable diff. */
function compactJson(schema: ServiceSchema): string {
  const block = (entries: Record<string, unknown>) =>
    `{\n${Object.entries(entries)
      .map(([k, v]) => `    ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
      .join('\n')}\n  }`;
  return [
    '{',
    `  service: ${JSON.stringify(schema.service)},`,
    `  endpoint: ${JSON.stringify(schema.endpoint)},`,
    `  namespace: ${JSON.stringify(schema.namespace)},`,
    `  types: ${block(schema.types)},`,
    `  arrays: ${block(schema.arrays)},`,
    `  operations: ${block(schema.operations)},`,
    '}',
  ].join('\n');
}

function render(schema: ServiceSchema): string {
  const lines = [
    '// Generated by scripts/generate.ts from the WSDL in wsdl/. Do not edit.',
    `import type { ServiceSchema } from '../schema.ts';`,
    '',
    `export const ${schema.service}Schema = ${compactJson(schema)} as const satisfies ServiceSchema;`,
    '',
  ];
  for (const [name, fields] of Object.entries(schema.types)) {
    lines.push(`export interface ${name} {`);
    for (const f of fields) lines.push(`  ${f.name}: ${tsType(f, schema, 'out')} | null;`);
    lines.push('}', '');
  }
  const opMap: string[] = [];
  for (const [name, op] of Object.entries(schema.operations)) {
    const type = pascal(name);
    lines.push(`export interface ${type}Input {`);
    for (const f of op.input) lines.push(`  ${f.name}?: ${tsType(f, schema, 'in')} | null;`);
    lines.push('}', '');
    lines.push(`export interface ${type}Output {`);
    for (const f of op.output) lines.push(`  ${f.name}: ${tsType(f, schema, 'out')} | null;`);
    lines.push('}', '');
    opMap.push(`  ${name}: { input: ${type}Input; output: ${type}Output };`);
  }
  lines.push(`export interface ${pascal(schema.service)}Operations {`, ...opMap, '}', '');
  const body = lines.join('\n');
  const imports = [
    /\bXmlElement\b/.test(body) && `import type { XmlElement } from '../xml.ts';`,
    /\bRawXml\b/.test(body) && `import type { RawXml } from '../soap.ts';`,
  ].filter(Boolean);
  return body.replace("import type { ServiceSchema } from '../schema.ts';", ["import type { ServiceSchema } from '../schema.ts';", ...imports].join('\n'));
}

mkdirSync('src/generated', { recursive: true });
for (const { service, wsdl } of SERVICES) {
  const schema = schemaOf(service, parseXml(readFileSync(wsdl, 'utf8')));
  writeFileSync(`src/generated/${service}.ts`, render(schema));
  console.log(`${service}: ${Object.keys(schema.operations).length} operations, ${Object.keys(schema.types).length} types`);
}
